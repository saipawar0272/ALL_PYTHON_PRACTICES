def findtotalmarks(sname,scls,**marks):
    tot=0
    print("student name={}".format(sname))
    print("student class={}".format(scls))
    print("----------------------")
    for k,v in marks.items():
        print("{}\t{}".format(k,v))
        tot=tot+v
    print("---------------")
    print("total marks={}".format(tot))

